"use client";

import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import dynamic from "next/dynamic";
import {
  apiGet, apiPost, formatCurrency, Transaction,
} from "@/lib/api";
import { useLang } from "@/components/LanguageProvider";
import { productCategoryKey } from "@/lib/i18n";

const EChartsReact = dynamic(() => import("echarts-for-react"), { ssr: false });

const HORIZONS = [30, 60, 90, 180];

const COLORS = {
  histIn: "#86efac",
  histOut: "#fca5a5",
  fcIn: "#16a34a",
  fcOut: "#dc2626",
  base: "#2563eb",
  sim: "#7c3aed",
};

function compact(v: number): string {
  const n = Math.abs(v);
  if (n >= 1000000) return (v / 1000000).toFixed(1) + "M";
  if (n >= 1000) return (v / 1000).toFixed(0) + "K";
  return String(Math.round(v));
}

function shortDate(s?: string | null): string {
  return s ? s.slice(5) : "";
}

function signed(v: number, currency = "CNY"): string {
  const prefix = v > 0 ? "+" : v < 0 ? "−" : "";
  return `${prefix}${formatCurrency(v, currency)}`;
}

function money(v: number | null | undefined, currency = "CNY"): string {
  if (v === null || v === undefined) return "—";
  return formatCurrency(v, currency);
}

type ProductRec = {
  id?: number;
  product_id: number;
  product_code?: string;
  product_name?: string;
  product_category?: string;
  category?: string;
  product_name_cn?: string;
  product_name_tw?: string;
  transaction_stage?: string;
  reason?: string;
  estimated_amount?: number;
  estimated_currency?: string;
  estimated_tenor_days?: number;
  confidence?: number;
};

export default function CashflowPage() {
  const { t, lang } = useLang();

  const [transactions, setTransactions] = useState<Transaction[]>([]);
  const [selectedTx, setSelectedTx] = useState<number>(1);
  const [horizon, setHorizon] = useState(90);
  const [forecast, setForecast] = useState<any>(null);
  const [scenarios, setScenarios] = useState<any[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");

  const [recommendations, setRecommendations] = useState<ProductRec[]>([]);
  const [recLoading, setRecLoading] = useState(false);

  const [selectedProduct, setSelectedProduct] = useState<ProductRec | null>(null);
  const [simulation, setSimulation] = useState<any>(null);
  const [simLoading, setSimLoading] = useState(false);
  const [paramValues, setParamValues] = useState<Record<string, any>>({});

  const simReq = useRef(0);
  const debounceTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const paramsRef = useRef<Record<string, any>>({});
  const prevProduct = useRef<ProductRec | null>(null);
  const autoGenerated = useRef<Set<number>>(new Set());
  const dirtyRef = useRef<Set<string>>(new Set());

  // ─── Load transactions once ───
  useEffect(() => {
    apiGet("/api/transactions").then((data) => {
      setTransactions(data.transactions || []);
    }).catch((e: any) => setError(e.message));
  }, []);

  // ─── Forecast + scenarios ───
  const loadForecast = useCallback(async () => {
    if (!selectedTx) return;
    setLoading(true);
    setError("");
    try {
      const [fc, sc] = await Promise.all([
        apiPost(`/api/cashflow/forecast?transaction_id=${selectedTx}&horizon_days=${horizon}&lang=${lang}`),
        apiPost(`/api/scenarios/simulate?transaction_id=${selectedTx}`),
      ]);
      setForecast(fc);
      setScenarios(sc.scenarios || []);
    } catch (e: any) {
      setError(e.message);
    }
    setLoading(false);
  }, [selectedTx, horizon, lang]);

  useEffect(() => {
    loadForecast();
  }, [loadForecast]);

  // ─── Recommendations for the selected transaction ───
  const loadRecommendations = useCallback(async () => {
    if (!selectedTx) return;
    setRecLoading(true);
    try {
      const data = await apiGet(`/api/recommendations?transaction_id=${selectedTx}&lang=${lang}`);
      let recs: ProductRec[] = data.recommendations || [];
      if (recs.length === 0 && !autoGenerated.current.has(selectedTx)) {
        autoGenerated.current.add(selectedTx);
        const gen = await apiPost(`/api/recommendations/generate?transaction_id=${selectedTx}&lang=${lang}`);
        recs = gen.recommendations || [];
      }
      setRecommendations(recs);
    } catch {
      setRecommendations([]);
    }
    setRecLoading(false);
  }, [selectedTx, lang]);

  useEffect(() => {
    loadRecommendations();
  }, [loadRecommendations]);

  // ─── Reset simulation when switching transaction ───
  useEffect(() => {
    setSelectedProduct(null);
    setSimulation(null);
    setParamValues({});
    paramsRef.current = {};
    dirtyRef.current = new Set();
    prevProduct.current = null;
    if (debounceTimer.current) clearTimeout(debounceTimer.current);
  }, [selectedTx]);

  // ─── Product simulation ───
  const runSimulation = useCallback(async (
    product: ProductRec,
    horizonDays: number,
    params: Record<string, any>,
    adoptDefaults: boolean,
  ) => {
    if (!product) return;
    const reqId = ++simReq.current;
    setSimLoading(true);
    try {
      const res = await apiPost("/api/cashflow/simulate-product", {
        transaction_id: selectedTx,
        product_id: product.product_id,
        horizon_days: horizonDays,
        lang,
        params,
      });
      if (reqId !== simReq.current) return;
      setSimulation(res);
      if (adoptDefaults) {
        const defaults = res.simulation?.params || {};
        paramsRef.current = defaults;
        setParamValues(defaults);
      }
    } catch (e: any) {
      if (reqId === simReq.current) setError(e.message);
    }
    if (reqId === simReq.current) setSimLoading(false);
  }, [selectedTx, lang]);

  useEffect(() => {
    if (!selectedProduct) {
      setSimulation(null);
      prevProduct.current = null;
      return;
    }
    const isNew = prevProduct.current !== selectedProduct;
    prevProduct.current = selectedProduct;
    if (isNew) {
      dirtyRef.current = new Set();
      paramsRef.current = {};
      setParamValues({});
      runSimulation(selectedProduct, horizon, {}, true);
    } else {
      runSimulation(selectedProduct, horizon, buildDirtyParams(), false);
    }
  }, [selectedProduct, horizon, lang, runSimulation]);

  // Only parameters the user actually edited are sent back, so untouched
  // fields keep their data-derived / assumption labels.
  const buildDirtyParams = () => {
    const out: Record<string, any> = {};
    dirtyRef.current.forEach((key) => {
      out[key] = paramsRef.current[key];
    });
    return out;
  };

  const updateParam = (key: string, value: any) => {
    const next = { ...paramsRef.current, [key]: value };
    paramsRef.current = next;
    dirtyRef.current.add(key);
    setParamValues(next);
    if (!selectedProduct) return;
    if (debounceTimer.current) clearTimeout(debounceTimer.current);
    debounceTimer.current = setTimeout(() => {
      runSimulation(selectedProduct, horizon, buildDirtyParams(), false);
    }, 400);
  };

  const selectProduct = (rec: ProductRec) => {
    const currentId = selectedProduct?.product_id;
    if (currentId === rec.product_id) return; // already selected
    setSelectedProduct(rec);
    setSimulation(null);
  };

  const regenerateRecommendations = async () => {
    setRecLoading(true);
    try {
      const gen = await apiPost(`/api/recommendations/generate?transaction_id=${selectedTx}&lang=${lang}`);
      setRecommendations(gen.recommendations || []);
    } catch (e: any) {
      setError(e.message);
    }
    setRecLoading(false);
  };

  const resetSimulation = () => {
    if (debounceTimer.current) clearTimeout(debounceTimer.current);
    simReq.current++;
    setSelectedProduct(null);
    setSimulation(null);
    setParamValues({});
    paramsRef.current = {};
    dirtyRef.current = new Set();
    prevProduct.current = null;
    setSimLoading(false);
  };

  const simData = simulation?.simulation;
  const simKpis = simData?.kpis;
  const baseKpis = forecast?.kpis;
  const simSeriesActive = !!simData?.series;

  // ─── Before / after chart ───
  const chartOption = useMemo(() => {
    // Prefer the merged series from the simulation (it keeps the base values
    // and adds sim_balance); fall back to the base forecast.
    const rows = simData?.series || forecast?.series || [];
    if (!rows.length) return {};
    const dates = rows.map((r: any) => r.date);
    const histIn = rows.map((r: any) => (r.is_forecast ? null : r.inflow || null));
    const histOut = rows.map((r: any) => (r.is_forecast ? null : -(r.outflow || 0) || null));
    const fcIn = rows.map((r: any) => (r.is_forecast ? r.inflow || null : null));
    const fcOut = rows.map((r: any) => (r.is_forecast ? -(r.outflow || 0) || null : null));
    const baseBalance = rows.map((r: any) => r.balance);
    const simBalance = rows.map((r: any) => r.sim_balance ?? null);

    const inName = t("cf_legend_inflow");
    const outName = t("cf_legend_outflow");
    const today = forecast.as_of;
    const low = baseKpis?.lowest_balance;
    const lowDate = baseKpis?.lowest_balance_date;
    const simLow = simKpis?.simulation?.lowest_balance;
    const simLowDate = simKpis?.simulation?.lowest_balance_date;

    return {
      animationDuration: 300,
      tooltip: {
        trigger: "axis",
        axisPointer: { type: "cross" },
        formatter: (ps: any) => {
          const i = ps?.[0]?.dataIndex;
          if (i === undefined || i < 0) return "";
          const r = rows[i];
          const tag = r.is_forecast ? t("cf_forecast_tag") : t("cf_actual");
          let html = `<b>${r.date}</b> <span style="color:#9b9ba3">· ${tag}</span><br/>`;
          html += `${inName}: ${formatCurrency(r.inflow, "CNY")}<br/>`;
          html += `${outName}: ${formatCurrency(r.outflow, "CNY")}<br/>`;
          html += `Net: ${signed(r.net)}<br/>`;
          if (r.balance !== null && r.balance !== undefined) {
            html += `${t("cf_legend_balance")}: ${formatCurrency(r.balance, "CNY")}<br/>`;
          }
          if (r.sim_balance !== null && r.sim_balance !== undefined && simSeriesActive) {
            html += `<span style="color:${COLORS.sim}">${t("cf_legend_sim_balance")}: ${formatCurrency(r.sim_balance, "CNY")}</span>`;
          }
          return html;
        },
      },
      legend: { top: 0, type: "scroll", itemWidth: 12, itemHeight: 8, textStyle: { fontSize: 11 } },
      grid: { left: "2%", right: "3%", top: 52, bottom: horizon >= 180 ? 44 : 24, containLabel: true },
      xAxis: {
        type: "category",
        data: dates,
        axisLabel: { fontSize: 10, formatter: (v: string) => shortDate(v) },
        axisTick: { show: false },
      },
      yAxis: [
        {
          type: "value",
          name: t("cf_event_amount"),
          nameTextStyle: { fontSize: 10, color: "#9b9ba3" },
          axisLabel: { fontSize: 10, formatter: (v: number) => compact(v) },
          splitLine: { lineStyle: { color: "#f0f0f2" } },
        },
        {
          type: "value",
          position: "right",
          axisLabel: { fontSize: 10, formatter: (v: number) => compact(v) },
          splitLine: { show: false },
        },
      ],
      dataZoom: horizon >= 180
        ? [{ type: "inside" }, { type: "slider", height: 14, bottom: 4, borderColor: "transparent" }]
        : [],
      series: [
        {
          name: `${inName} · ${t("cf_historical")}`,
          type: "bar",
          stack: "histIn",
          data: histIn,
          barMaxWidth: 8,
          itemStyle: { color: COLORS.histIn },
        },
        {
          name: `${outName} · ${t("cf_historical")}`,
          type: "bar",
          stack: "histOut",
          data: histOut,
          barMaxWidth: 8,
          itemStyle: { color: COLORS.histOut },
        },
        {
          name: `${inName} · ${t("cf_forecast_tag")}`,
          type: "bar",
          stack: "fcIn",
          data: fcIn,
          barMaxWidth: 10,
          itemStyle: { color: COLORS.fcIn },
        },
        {
          name: `${outName} · ${t("cf_forecast_tag")}`,
          type: "bar",
          stack: "fcOut",
          data: fcOut,
          barMaxWidth: 10,
          itemStyle: { color: COLORS.fcOut },
        },
        {
          name: t("cf_legend_balance"),
          type: "line",
          yAxisIndex: 1,
          data: baseBalance,
          smooth: false,
          symbol: "none",
          lineStyle: { width: 2.5, color: COLORS.base },
          itemStyle: { color: COLORS.base },
          markLine: {
            symbol: "none",
            lineStyle: { color: "#9b9ba3", type: "dashed", width: 1 },
            label: { formatter: t("cf_today"), fontSize: 10, color: "#9b9ba3" },
            data: [{ xAxis: today }],
          },
          markPoint: low !== null && low !== undefined && lowDate
            ? {
                symbolSize: 58,
                itemStyle: { color: COLORS.base },
                label: { show: false },
                data: [{ coord: [lowDate, low], value: low }],
              }
            : undefined,
        },
        ...(simSeriesActive
          ? [{
              name: t("cf_legend_sim_balance"),
              type: "line",
              yAxisIndex: 1,
              data: simBalance,
              symbol: "none",
              lineStyle: { width: 2.5, color: COLORS.sim },
              itemStyle: { color: COLORS.sim },
              markPoint: simLow !== null && simLow !== undefined && simLowDate
                ? {
                    symbolSize: 58,
                    itemStyle: { color: COLORS.sim },
                    label: { show: false },
                    data: [{ coord: [simLowDate, simLow], value: simLow }],
                  }
                : undefined,
            }]
          : []),
      ],
    };
  }, [forecast, simulation, simData, horizon, lang, simSeriesActive, t, simKpis, baseKpis]);

  // ─── Scenario comparison chart (existing section) ───
  const scenarioOption = scenarios.length > 0 ? {
    tooltip: { trigger: "axis" },
    legend: { top: 0 },
    grid: { left: "3%", right: "4%", bottom: "3%", top: 40, containLabel: true },
    xAxis: {
      type: "category",
      data: scenarios.map((s) => s.scenario_name),
      axisLabel: { fontSize: 10, rotate: 20 },
    },
    yAxis: {
      type: "value",
      axisLabel: {
        fontSize: 11,
        formatter: (v: number) => v >= 1000000 ? (v / 1000000).toFixed(1) + "M" : v >= 1000 ? (v / 1000).toFixed(0) + "K" : v.toString(),
      },
    },
    series: [
      {
        name: "Max Funding Gap",
        type: "bar",
        data: scenarios.map((s) => Math.abs(s.max_funding_gap)),
        itemStyle: {
          color: (params: any) => {
            const colors = ["#a91624", "#f59e0b", "#8b5cf6", "#2563eb", "#dc2626"];
            return colors[params.dataIndex % colors.length];
          },
        },
        label: {
          show: true,
          position: "top",
          formatter: (p: any) => p.value >= 1000000 ? (p.value / 1000000).toFixed(1) + "M" : (p.value / 1000).toFixed(0) + "K",
          fontSize: 10,
        },
      },
    ],
  } : {};

  const kpiBalance = simKpis?.simulation?.projected_closing_balance ?? baseKpis?.projected_closing_balance;
  const kpiBalanceDelta = simKpis
    ? kpiBalance - simKpis.base.projected_closing_balance
    : null;
  const shortfall = simKpis?.shortfall_risk;
  const horizonLabel = `cf_h${horizon}`;
  const selectedId = selectedProduct?.product_id;
  const selectedName = simulation?.product?.product_name
    || selectedProduct?.product_name
    || selectedProduct?.product_name_cn
    || "";

  const sourceBadge = (source: string) => {
    const map: Record<string, { key: string; cls: string }> = {
      unset: { key: "cf_pending_config", cls: "bg-[#fef3c7] text-[#92400e]" },
      assumption: { key: "cf_assumption_tag", cls: "bg-[#e0f2fe] text-[#075985]" },
      recommendation: { key: "cf_rec_data", cls: "bg-[#dcfce7] text-[#166534]" },
      derived: { key: "cf_derived", cls: "bg-[#f7f7f8] text-[#6b6b73]" },
      user: { key: "cf_user_input", cls: "bg-[#ede9fe] text-[#5b21b6]" },
      product: { key: "cf_product_data", cls: "bg-[#f7f7f8] text-[#6b6b73]" },
    };
    return map[source] || map.derived;
  };

  return (
    <div className="fade-in">
      <div className="mb-5">
        <h1 className="text-2xl font-bold mb-1">{t("cf_title")}</h1>
        <p className="text-sm text-[#6b6b73]">{t("cf_subtitle")}</p>
      </div>

      {/* Transaction + horizon selectors */}
      <div className="flex flex-wrap items-center gap-2 mb-4">
        {transactions.map((tr) => (
          <button
            key={tr.id}
            onClick={() => setSelectedTx(tr.id)}
            className={`px-3 py-1.5 rounded-lg text-sm border transition ${
              selectedTx === tr.id
                ? "bg-[#a91624] text-white border-[#a91624]"
                : "bg-white border-[#e5e5e8] hover:border-[#a91624]"
            }`}
          >
            {tr.tx_ref}
          </button>
        ))}
        <div className="ml-auto flex items-center gap-1.5">
          <span className="text-xs text-[#9b9ba3] mr-1">{t("cf_horizon")}</span>
          <div className="flex rounded-lg border border-[#e5e5e8] bg-white overflow-hidden">
            {HORIZONS.map((h) => (
              <button
                key={h}
                onClick={() => { setHorizon(h); setSimulation(null); }}
                className={`px-2.5 py-1 text-xs transition ${
                  horizon === h ? "bg-[#a91624] text-white" : "text-[#6b6b73] hover:bg-[#f7f7f8]"
                }`}
              >
                {t(`cf_h${h}`)}
              </button>
            ))}
          </div>
        </div>
      </div>

      {error && (
        <div className="mb-4 p-3 rounded-lg bg-[#fef2f2] border border-[#fecaca] text-xs text-[#991b1b]">
          {error}
        </div>
      )}

      {loading || !forecast ? (
        <div className="py-16 text-center text-[#9b9ba3]">{t("loading")}</div>
      ) : (
        <div className="space-y-4">
          {/* KPI cards */}
          <div className="grid grid-cols-2 md:grid-cols-3 xl:grid-cols-5 gap-3">
            <div className="card" style={{ padding: 14 }}>
              <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_balance")}</div>
              <div className="text-xl font-bold text-[#1a1a1a]">
                {money(kpiBalance)}
              </div>
              {kpiBalanceDelta !== null && (
                <div className={`text-xs mt-0.5 ${kpiBalanceDelta >= 0 ? "text-[#16a34a]" : "text-[#dc2626]"}`}>
                  {signed(kpiBalanceDelta)} vs {t("cf_base_forecast")}
                </div>
              )}
              <div className="text-[11px] text-[#9b9ba3] mt-1">
                {t("cf_min_balance")}: {money(simKpis?.simulation?.lowest_balance ?? baseKpis?.lowest_balance)}
                {" · "}
                {simKpis?.simulation?.lowest_balance_date ?? baseKpis?.lowest_balance_date ?? "—"}
              </div>
            </div>

            <div className="card" style={{ padding: 14 }}>
              <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_liquidity")}</div>
              <div className="text-xl font-bold text-[#16a34a]">
                {simKpis ? money(simKpis.additional_liquidity) : "—"}
              </div>
              <div className="text-[11px] text-[#9b9ba3] mt-1">
                {simKpis ? t("cf_simulated") : t("cf_no_product_selected")}
              </div>
            </div>

            <div className="card" style={{ padding: 14 }}>
              <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_cost")}</div>
              <div className="text-xl font-bold text-[#a91624]">
                {simKpis ? money(simKpis.financing_cost) : "—"}
              </div>
              <div className="text-[11px] text-[#9b9ba3] mt-1">
                {simKpis ? t("cf_cost_note") : t("cf_no_product_selected")}
              </div>
            </div>

            <div className="card" style={{ padding: 14 }}>
              <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_improvement")}</div>
              <div className={`text-xl font-bold ${simKpis && simKpis.cash_flow_improvement < 0 ? "text-[#dc2626]" : "text-[#16a34a]"}`}>
                {simKpis ? signed(simKpis.cash_flow_improvement) : "—"}
              </div>
              <div className="text-[11px] text-[#9b9ba3] mt-1">
                {simKpis ? `${t("cf_min_balance")} · ${simKpis.shortfall_risk.label}` : t("cf_no_product_selected")}
              </div>
            </div>

            <div className="card" style={{ padding: 14 }}>
              <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_shortfall")}</div>
              <div className={`text-xl font-bold ${((shortfall?.simulation_shortfall_amount ?? baseKpis?.shortfall_amount) || 0) > 0 ? "text-[#dc2626]" : "text-[#16a34a]"}`}>
                {((shortfall?.simulation_shortfall_amount ?? baseKpis?.shortfall_amount) || 0) > 0
                  ? money(shortfall?.simulation_shortfall_amount ?? baseKpis?.shortfall_amount)
                  : t("cf_no_shortfall")}
              </div>
              <div className="text-[11px] text-[#9b9ba3] mt-1">
                {simKpis
                  ? `${t("cf_base_forecast")}: ${money(simKpis.base.shortfall_amount)} → ${t("cf_simulated")}: ${money(simKpis.simulation.shortfall_amount)}`
                  : `${baseKpis?.shortfall_days || 0} ${t("cf_days")}`}
              </div>
            </div>
          </div>

          {/* Status chips */}
          <div className="flex flex-wrap items-center gap-2 text-xs">
            <span className="px-2 py-0.5 rounded bg-[#f7f7f8] text-[#6b6b73]">● {t("cf_actual")}</span>
            <span className="px-2 py-0.5 rounded bg-[#dcfce7] text-[#166534]">● {t("cf_forecast_tag")}</span>
            {simKpis && <span className="px-2 py-0.5 rounded bg-[#ede9fe] text-[#5b21b6]">● {t("cf_simulated")}</span>}
            {selectedProduct && (
              <span className="px-2 py-0.5 rounded bg-[#a91624] text-white">
                {t("cf_selected_product")}: {selectedName}
              </span>
            )}
            {selectedProduct && (
              <button onClick={resetSimulation} className="ml-auto text-[#a91624] underline">
                {t("cf_reset_sim")}
              </button>
            )}
          </div>

          {/* Before / after forecast chart */}
          <div className="card">
            <div className="flex items-center justify-between mb-2 flex-wrap gap-2">
              <h2 className="font-bold">{t("cf_before_after")}</h2>
              <span className="text-xs text-[#9b9ba3]">
                {t("cf_horizon")}: {t(horizonLabel)} · {t("cf_base_forecast")}
                {simKpis ? ` vs ${t("cf_product_forecast")}` : ""}
              </span>
            </div>
            <EChartsReact option={chartOption} style={{ height: 360 }} notMerge />
            <p className="text-[11px] text-[#9b9ba3] mt-2">{t("cf_forecast_note")}</p>
          </div>

          {/* Product simulation parameters */}
          {selectedProduct && (
            <div className="card">
              <div className="flex items-start justify-between gap-2 mb-3 flex-wrap">
                <div>
                  <h2 className="font-bold">{t("cf_sim_params")}</h2>
                  <div className="text-xs text-[#6b6b73] mt-0.5">
                    {selectedName}
                    {simulation?.product?.category && (
                      <span className="ml-2 px-2 py-0.5 rounded bg-[#f7f7f8] text-[#6b6b73]">
                        {t(productCategoryKey(simulation.product.category) || "")}
                      </span>
                    )}
                  </div>
                </div>
                <button onClick={resetSimulation} className="btn-secondary btn-sm">
                  {t("cf_reset_sim")}
                </button>
              </div>

              {simLoading && (
                <div className="text-xs text-[#9b9ba3] mb-2">{t("cf_loading_sim")}</div>
              )}

              {simulation && (
                <>
                  <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3">
                    {(simulation.simulation.parameter_schema || []).map((p: any) => {
                      const badge = sourceBadge(p.source);
                      const label = t(`cf_param_${p.key}`);
                      const value = paramValues[p.key];
                      return (
                        <div key={p.key} className="p-2.5 rounded-lg border border-[#e5e5e8]">
                          <div className="flex items-center justify-between gap-1 mb-1">
                            <span className="text-xs text-[#6b6b73]">{label}</span>
                            <span className={`text-[10px] px-1.5 py-0.5 rounded ${badge.cls}`}>
                              {t(badge.key)}
                            </span>
                          </div>
                          {p.editable ? (
                            p.options?.length ? (
                              <select
                                value={value ?? p.value ?? ""}
                                onChange={(e) => updateParam(p.key, e.target.value)}
                                className="w-full text-sm border border-[#e5e5e8] rounded px-2 py-1 bg-white"
                              >
                                {p.options.map((opt: string) => (
                                  <option key={opt} value={opt}>
                                    {p.key === "repayment_method"
                                      ? t(`cf_repay_${opt}`)
                                      : simulation.simulation.receivable?.eligible_receivables?.[Number(opt)]
                                        ? `${simulation.simulation.receivable.eligible_receivables[Number(opt)].date} · ${formatCurrency(simulation.simulation.receivable.eligible_receivables[Number(opt)].amount, simulation.simulation.receivable.eligible_receivables[Number(opt)].currency)}`
                                        : opt}
                                  </option>
                                ))}
                              </select>
                            ) : (
                              <input
                                type="number"
                                value={value ?? ""}
                                placeholder={p.source === "unset" ? t("cf_pending_config") : ""}
                                onChange={(e) => updateParam(
                                  p.key,
                                  e.target.value === "" ? null : Number(e.target.value),
                                )}
                                className="w-full text-sm border border-[#e5e5e8] rounded px-2 py-1"
                                step={p.unit === "%" || p.unit === "% p.a." ? 0.1 : p.unit === "days" ? 1 : 1000}
                              />
                            )
                          ) : (
                            <div className="text-sm text-[#1a1a1a]">
                              {p.value === null || p.value === undefined ? "—" : `${p.value} ${p.unit === "%" ? "%" : p.unit === "" ? "" : p.unit}`}
                            </div>
                          )}
                        </div>
                      );
                    })}
                  </div>

                  {simulation.simulation.unconfigured?.length > 0 && (
                    <div className="mt-3 p-2.5 rounded-lg bg-[#fffbeb] border border-[#fde68a] text-xs text-[#92400e]">
                      {t("cf_pending_note")}{" "}
                      {simulation.simulation.unconfigured.map((key: string) => t(`cf_param_${key}`)).join("、")}
                    </div>
                  )}

                  {simulation.simulation.assumptions?.length > 0 && (
                    <div className="mt-3 p-2.5 rounded-lg bg-[#f0f9ff] border border-[#bae6fd] text-xs text-[#075985]">
                      {t("cf_assumption_note")}{" "}
                      {simulation.simulation.assumptions
                        .filter((a: any) => !simulation.simulation.unconfigured?.includes(a.key))
                        .map((a: any) => t(`cf_param_${a.key}`))
                        .join("、")}
                    </div>
                  )}

                  {simulation.simulation.notes?.length > 0 && (
                    <ul className="mt-3 space-y-1 text-xs text-[#6b6b73] list-disc pl-4">
                      {simulation.simulation.notes.map((n: any, i: number) => (
                        <li key={i}>{n.text}</li>
                      ))}
                    </ul>
                  )}

                  {/* Before vs after */}
                  <div className="mt-4 grid grid-cols-1 md:grid-cols-3 gap-3 text-sm">
                    <div className="p-3 rounded-lg bg-[#f7f7f8]">
                      <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_base_closing")}</div>
                      <div className="font-bold">{money(simKpis?.base?.projected_closing_balance)}</div>
                    </div>
                    <div className="p-3 rounded-lg bg-[#f5f3ff]">
                      <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_sim_closing")}</div>
                      <div className="font-bold text-[#5b21b6]">
                        {money(simKpis?.simulation?.projected_closing_balance)}
                      </div>
                    </div>
                    <div className="p-3 rounded-lg bg-[#f7f7f8]">
                      <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_kpi_cost")}</div>
                      <div className="font-bold text-[#a91624]">{money(simKpis?.financing_cost)}</div>
                    </div>
                  </div>

                  {simulation.simulation.summary && (
                    <div className="mt-3 text-sm text-[#6b6b73]">
                      <span className="font-medium text-[#1a1a1a]">{t("cf_sim_summary")}: </span>
                      {simulation.simulation.summary}
                    </div>
                  )}

                  {/* Product cash-flow events */}
                  <div className="mt-4">
                    <h3 className="font-bold text-sm mb-2">{t("cf_sim_events")}</h3>
                    {simulation.simulation.events?.length ? (
                      <div className="overflow-x-auto">
                        <table className="w-full text-xs">
                          <thead>
                            <tr className="border-b border-[#e5e5e8] text-left text-[#9b9ba3]">
                              <th className="py-1.5 pr-3">{t("cf_event_date")}</th>
                              <th className="py-1.5 pr-3">{t("cf_event_desc")}</th>
                              <th className="py-1.5 pr-3 text-right">{t("cf_event_amount")}</th>
                            </tr>
                          </thead>
                          <tbody>
                            {[...simulation.simulation.events]
                              .sort((a: any, b: any) => a.date.localeCompare(b.date))
                              .map((ev: any, i: number) => (
                                <tr key={i} className="border-b border-[#f0f0f2]">
                                  <td className="py-1.5 pr-3 whitespace-nowrap">{ev.date}</td>
                                  <td className="py-1.5 pr-3">
                                    {ev.description}
                                    {ev.note && <span className="text-[#9b9ba3]"> · {ev.note}</span>}
                                  </td>
                                  <td className={`py-1.5 pr-3 text-right font-medium ${ev.amount >= 0 ? "text-[#16a34a]" : "text-[#dc2626]"}`}>
                                    {signed(ev.amount, ev.currency || "CNY")}
                                  </td>
                                </tr>
                              ))}
                          </tbody>
                        </table>
                      </div>
                    ) : (
                      <p className="text-xs text-[#9b9ba3]">{t("cf_no_events")}</p>
                    )}
                  </div>
                </>
              )}
            </div>
          )}

          {/* Recommended products */}
          <div className="card">
            <div className="flex items-start justify-between gap-2 mb-1 flex-wrap">
              <div>
                <h2 className="font-bold">{t("cf_recommended_products")}</h2>
                <p className="text-xs text-[#9b9ba3] mt-0.5">{t("cf_select_product_hint")}</p>
              </div>
              <button
                onClick={regenerateRecommendations}
                className="btn-secondary btn-sm"
                disabled={recLoading}
              >
                {recLoading ? t("loading") : (recommendations.length ? t("rm_regen_recs") : t("cf_generate_recs"))}
              </button>
            </div>

            <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-3 mt-3">
              {recommendations.map((rec) => {
                const selected = selectedId === rec.product_id;
                const catKey = productCategoryKey(rec.product_category || rec.category);
                return (
                  <button
                    key={rec.product_id}
                    onClick={() => selectProduct(rec)}
                    className={`text-left p-3 rounded-lg border transition ${
                      selected
                        ? "border-[#7c3aed] ring-2 ring-[#7c3aed]/30 bg-[#faf5ff]"
                        : "border-[#e5e5e8] bg-white hover:border-[#a91624]"
                    }`}
                  >
                    <div className="flex items-start justify-between gap-2 mb-1">
                      <div className="font-medium text-sm">
                        {rec.product_name || rec.product_name_cn || rec.transaction_stage}
                      </div>
                      <div className="flex flex-col items-end gap-1 shrink-0">
                        {catKey && (
                          <span className="text-[10px] px-1.5 py-0.5 rounded bg-[#f7f7f8] text-[#6b6b73]">
                            {t(catKey)}
                          </span>
                        )}
                        {selected && (
                          <span className="text-[10px] px-1.5 py-0.5 rounded bg-[#7c3aed] text-white">
                            {t("cf_selected_product")}
                          </span>
                        )}
                      </div>
                    </div>
                    <p className="text-xs text-[#6b6b73] line-clamp-2 mb-2">{rec.reason}</p>
                    <div className="flex flex-wrap gap-x-3 gap-y-1 text-[11px] text-[#9b9ba3]">
                      <span>
                        {formatCurrency(rec.estimated_amount || 0, rec.estimated_currency || "CNY")}
                      </span>
                      <span>{rec.estimated_tenor_days || 0} {t("cf_days")}</span>
                      {rec.confidence !== undefined && (
                        <span>{Math.round((rec.confidence || 0) * 100)}%</span>
                      )}
                    </div>
                  </button>
                );
              })}
            </div>

            {!recLoading && recommendations.length === 0 && (
              <p className="text-xs text-[#9b9ba3] mt-3">{t("cf_no_recs")}</p>
            )}
            <p className="text-[11px] text-[#9b9ba3] mt-3">{t("rec_source_note")}</p>
          </div>

          {/* Legacy funding gap + summary */}
          {forecast?.funding_gap && (
            <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
              <div className="card">
                <h2 className="font-bold mb-3">{t("cf_funding_gap")}</h2>
                {forecast.funding_gap.gaps?.length > 0 ? (
                  <div className="space-y-3">
                    {forecast.funding_gap.gaps.map((gap: any, i: number) => (
                      <div key={i} className="p-3 rounded-lg bg-[#fef3c7] border border-[#f0d060]">
                        <div className="flex items-center justify-between mb-2">
                          <span className="text-sm font-medium">{t("cf_gap_currency")}: {gap.gap_currency}</span>
                          <span className="text-lg font-bold text-[#dc2626]">
                            {formatCurrency(gap.gap_amount, gap.gap_currency)}
                          </span>
                        </div>
                        <div className="text-xs text-[#6b6b73] space-y-1">
                          <div>{t("cf_duration")}: {gap.gap_duration_days} {t("cf_days")}</div>
                          <div>{t("cf_start_date")}: {gap.gap_start_date}</div>
                          {gap.gap_end_date && <div>{t("cf_end_date")}: {gap.gap_end_date}</div>}
                        </div>
                      </div>
                    ))}
                  </div>
                ) : (
                  <div className="text-center py-8 text-sm text-[#9b9ba3]">
                    {t("cf_no_gap")}
                  </div>
                )}
                <div className="mt-3 pt-3 border-t border-[#e5e5e8]">
                  <div className="text-xs text-[#9b9ba3] mb-1">{t("cf_primary_cause")}</div>
                  <p className="text-sm text-[#6b6b73]">{forecast.funding_gap.primary_cause}</p>
                </div>
              </div>

              <div className="card">
                <h2 className="font-bold mb-3">{t("cf_summary")}</h2>
                <p className="text-sm text-[#6b6b73] mb-3">{forecast.summary}</p>
                <div className="space-y-2 text-xs">
                  <div className="flex justify-between">
                    <span className="text-[#9b9ba3]">{t("cf_kpi_balance")}</span>
                    <span className="font-medium">{money(baseKpis?.projected_closing_balance)}</span>
                  </div>
                  <div className="flex justify-between">
                    <span className="text-[#9b9ba3]">{t("cf_min_balance")}</span>
                    <span>{money(baseKpis?.lowest_balance)} · {baseKpis?.lowest_balance_date || "—"}</span>
                  </div>
                  <div className="flex justify-between">
                    <span className="text-[#9b9ba3]">{t("cf_min_liquidity")} (CNY)</span>
                    <span>{money(forecast.funding_gap.min_liquidity_buffer?.CNY)}</span>
                  </div>
                </div>
              </div>
            </div>
          )}

          {/* Scenario simulation (existing) */}
          <div className="card">
            <h2 className="font-bold mb-2">{t("cf_scenario_sim")}</h2>
            <EChartsReact option={scenarioOption} style={{ height: 300 }} />
            <p className="illustrative-note mt-2">{t("boundary_illustrative")}</p>
          </div>

          <div className="card">
            <h2 className="font-bold mb-3">{t("cf_scenario_detail")}</h2>
            <div className="overflow-x-auto">
              <table className="w-full text-sm">
                <thead>
                  <tr className="border-b border-[#e5e5e8] text-left">
                    <th className="py-2 pr-4">{t("cf_scenario")}</th>
                    <th className="py-2 pr-4">{t("cf_params")}</th>
                    <th className="py-2 pr-4">{t("cf_max_gap")}</th>
                    <th className="py-2 pr-4">{t("cf_main_risk")}</th>
                  </tr>
                </thead>
                <tbody>
                  {scenarios.map((sc) => (
                    <tr key={sc.scenario_name} className="border-b border-[#f0f0f2]">
                      <td className="py-2 pr-4 font-medium">{sc.scenario_name}</td>
                      <td className="py-2 pr-4 text-xs text-[#6b6b73]">
                        {Object.entries(sc.parameters).map(([k, v]) => `${k}: ${v}`).join(", ")}
                      </td>
                      <td className="py-2 pr-4">
                        <span className="font-bold text-[#dc2626]">
                          {formatCurrency(Math.abs(sc.max_funding_gap), sc.gap_currency)}
                        </span>
                      </td>
                      <td className="py-2 pr-4">
                        <span className="text-xs px-2 py-0.5 rounded risk-medium">{sc.main_risk}</span>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          </div>

          <div className="card text-center">
            <a href={`/app/report?tx=${selectedTx}`} className="btn-primary btn-sm">
              {t("cf_gen_report")}
            </a>
          </div>
        </div>
      )}
    </div>
  );
}
